#!/usr/bin/env python3
"""Point a T7Zombies checkout at Waxley's local asset ids (run on a scratch copy, never the repo).

  python3 -I tools/t7_localize.py [~/code/active/games/roblox/T7Zombies/waxley/t7]

Rewrites, in place:
  src/Server/Game/CastleData.luau   regenerated by bo3map's roblox_luau.py from the castle export with
                                    local pack AND texture ids (assets/maps/zm_castle.json, from
                                    tools/bo3_local.py): the repo's copy predates the texture uploads, so
                                    its pieces have no textures. Withheld textures (no_upload.json) stay
                                    untextured, as in the game.
  src/Server/Game/CastleMap.luau    "pending:sky_<face>" -> the sky faces' local ids (sky:zm_castle@N/<Face>)
  src/Shared/ZombieAnims/ids.luau   emptied, and ZombieClient ignores KeyframeSequence AssetId attributes: the
                                    sequences are registered locally instead
  src/Server/Game/NachtData.luau    uploaded pack ids -> local packs (assets/maps/zm_prototype.json)
  src/Shared/SoundBank.luau         sheets castle / castle_vox / castle_2d -> local ids (registry keys
                                    sound:t7/<sheet>, from tools/local_asset.py); those leave `pending`
  src/Server/Game/Bo3Map.luau       hull brushes are built with CreateMeshPartAsync(..., Hull) instead of
                                    cloning the pack template: Waxley's local MeshParts have no PhysicsData,
                                    so a cloned template collides as its bounding box (slower load, right nav)
Fails if an id is missing rather than leaving the file half done. Safe to run twice.
"""
import json
import os
import re
import subprocess
import sys
import tempfile

STORE = os.path.join(os.environ.get("WAXLEY_DATA", os.path.expanduser("~/.local/share/waxley")), "assets")
SHEETS = ("castle", "castle_vox", "castle_2d")
CASTLE = os.path.expanduser("~/code/ref/bo3-maps/zm_castle")
BO3MAP = os.path.expanduser("~/code/active/projects/bo3map")


def castle_data(out, local):
    """CastleData from the export, with Waxley's ids for the packs (ids_models.json) and every texture
    (images.json), via a scratch map dir of symlinks (the export itself is left alone)"""
    with tempfile.TemporaryDirectory() as tmp:
        os.mkdir(os.path.join(tmp, "roblox"))
        for f in os.listdir(CASTLE):
            if f != "roblox":
                os.symlink(os.path.join(CASTLE, f), os.path.join(tmp, f))
        for f in os.listdir(os.path.join(CASTLE, "roblox")):
            if f not in ("images.json", "ids_models.json"):
                os.symlink(os.path.join(CASTLE, "roblox", f), os.path.join(tmp, "roblox", f))
        json.dump({k: str(v) for k, v in local["images"].items()}, open(os.path.join(tmp, "roblox", "images.json"), "w"))
        json.dump({k.replace("pending:", ""): str(v) for k, v in local["packs"].items()},
                  open(os.path.join(tmp, "roblox", "ids_models.json"), "w"))
        subprocess.run([sys.executable, "-I", os.path.join(BO3MAP, "roblox_luau.py"), tmp, out], check=True,
                       stdout=subprocess.DEVNULL)


def main(root):
    if os.path.isdir(os.path.join(root, ".git")):
        sys.exit(f"{root} is a git checkout: run this on a scratch copy")
    local = json.load(open(os.path.join(STORE, "maps", "zm_castle.json")))
    packs = local["packs"]
    reg = json.load(open(os.path.join(STORE, "local.json")))

    p = os.path.join(root, "src/Server/Game/CastleData.luau")
    castle_data(p, local)
    s = open(p).read()
    print(f"{p}: regenerated, {s.count('rbxassetid://')} textured pieces")
    missing = sorted(set(re.findall(r'"(pending:[^"]+)"', s)) - set(packs))
    if missing:
        sys.exit(f"no local id for {missing[:5]} ({len(missing)}): rerun tools/bo3_local.py")
    s, n = re.subn(r'"(pending:[^"]+)"', lambda m: '"%d"' % packs[m.group(1)], s)
    open(p, "w").write(s)
    print(f"{p}: {n} pack ids")

    p = os.path.join(root, "src/Server/Game/CastleMap.luau")
    s = open(p).read()
    for face in ("bk", "dn", "ft", "lf", "rt", "up"):
        key = f"sky:zm_castle@3/{face.capitalize()}"  # (@N: new ids per export, Studio caches by id)
        if f'"pending:sky_{face}"' in s:
            if key not in reg:
                sys.exit(f"no local id for {key}: run tools/local_asset.py on the sky faces")
            s = s.replace(f'"pending:sky_{face}"', f'"rbxassetid://{reg[key]}"')
    open(p, "w").write(s)
    print(f"{p}: sky faces -> local ids")

    # Nacht: its packs are uploaded FBX models (the ledger can only hand back the .fbx, which LoadAsset
    # can't read): point each at the local pack built from the same export (bo3_local.py zm_prototype)
    p = os.path.join(root, "src/Server/Game/NachtData.luau")
    nacht = os.path.join(STORE, "maps", "zm_prototype.json")
    if os.path.exists(p) and os.path.exists(nacht):
        npacks = json.load(open(nacht))["packs"]
        s = open(p).read()
        s, n = re.subn(r'"(?:\d+|pending:fbx_pack_\d+)", -- (fbx_pack_\d+)', lambda m: f'"{npacks["pending:" + m.group(1)]}", -- {m.group(1)} (Waxley local)', s)
        # pieces grafted from another map's export (bo3map graft_model.py) aren't uploaded yet: t = nil,
        # their texture named in the line's comment
        nimg = json.load(open(nacht))["images"]
        s, g = re.subn(r't = nil(, r = "prop"[^\n]*-- \(grafted from \w+: (\w+)\))',
                       lambda m: (f't = "rbxassetid://{nimg[m.group(2)]}"' if m.group(2) in nimg else "t = nil") + m.group(1), s)
        open(p, "w").write(s)
        print(f"{p}: {n} pack ids -> local, {g} grafted pieces textured")
        # its textures are the image ids behind uploaded decals (images.json: name -> image id); the ledger
        # only knows the decal ids, so map each image id to the local copy of the same texture
        images = os.path.expanduser("~/code/ref/bo3-maps/zm_prototype/roblox/images.json")
        if os.path.exists(images):
            by_id = {str(v): k for k, v in json.load(open(images)).items()}
            local_img = json.load(open(nacht))["images"]
            s = open(p).read()
            s, n = re.subn(r'"rbxassetid://(\d+)"', lambda m: f'"rbxassetid://{local_img[by_id[m.group(1)]]}"'
                           if by_id.get(m.group(1)) in local_img else m.group(0), s)
            open(p, "w").write(s)
            print(f"{p}: {n} texture refs -> local")

    # zombie animations: the uploaded ids can't be served offline; without them ZombieClient registers
    # the KeyframeSequences locally (KeyframeSequenceProvider), which works in Studio
    p = os.path.join(root, "src/Shared/ZombieAnims/ids.luau")
    if os.path.exists(p):
        open(p, "w").write("--!strict\n-- (Waxley: uploaded animation ids dropped; the sequences are registered locally)\nreturn {}\n")
        print(f"{p}: emptied")
    # (each KeyframeSequence also carries its uploaded id as attribute AssetId)
    p = os.path.join(root, "src/Client/ZombieClient.luau")
    s = open(p).read()
    a = 'local assetId = uploaded[ks.Name] or ks:GetAttribute("AssetId")'
    if a in s:
        s = s.replace(a, 'local assetId = nil -- (Waxley: register locally)')
        open(p, "w").write(s)
        print(f"{p}: animations registered locally")
    elif "(Waxley: register locally)" not in s:
        sys.exit(f"{p}: ZombieClient changed, update t7_localize")

    p = os.path.join(root, "src/Shared/SoundBank.luau")
    s = open(p).read()
    ids = {}
    for sheet in SHEETS:
        key = f"sound:t7/{sheet}"
        if key not in reg:
            sys.exit(f"no local id for {key}: run tools/local_asset.py {key} tools/sounds/out/t7_{sheet}.wav")
        ids[sheet] = reg[key]
    m = re.search(r"\tsheets = \{\n(.*?)\n\t\},", s, re.S)
    lines = [l for l in m.group(1).split("\n") if not re.match(r"\t\t(%s) = " % "|".join(SHEETS), l)]
    lines += [f'\t\t{k} = "rbxassetid://{v}", -- Waxley local id' for k, v in ids.items()]
    s = s[:m.start(1)] + "\n".join(lines) + s[m.end(1):]
    pm = re.search(r"\tpending = \{([^}]*)\},", s)
    if pm:
        left = [x for x in re.findall(r'"([^"]+)"', pm.group(1)) if x not in SHEETS]
        s = s[:pm.start()] + "\tpending = {%s}," % ", ".join(f'"{x}"' for x in left) + s[pm.end():]
    open(p, "w").write(s)
    print(f"{p}: " + ", ".join(f"{k}={v}" for k, v in ids.items()))

    p = os.path.join(root, "src/Server/Game/Bo3Map.luau")
    s = open(p).read()
    loop = "\t\tfor _, h in D.hulls do\n"
    clone = '\t\t\t\tlocal p = tpl:Clone()\n\t\t\t\tp.Name = "Brush"'
    if "(Waxley) local pack MeshParts" not in s:
        if loop not in s or clone not in s:
            sys.exit(f"{p}: hull brush loop not found (Bo3Map changed?)")
        pre = ("\t\t-- (Waxley) local pack MeshParts carry no collision data: compute every hull up front, 32 at a time\n"
               "\t\tlocal hullMade: { [string]: MeshPart } = {}\n"
               "\t\tparallel(cfg.name, D.hulls, 32, function(h)\n"
               "\t\t\tlocal tpl = templates[h[1]]\n"
               "\t\t\tif tpl and bit32.band(h[2], 7) ~= 0 then\n"
               "\t\t\t\thullMade[h[1]] = AssetService:CreateMeshPartAsync(tpl.MeshId, { CollisionFidelity = Enum.CollisionFidelity.Hull })\n"
               "\t\t\tend\n"
               "\t\tend)\n")
        s = s.replace(loop, pre + loop, 1)
        s = s.replace(clone, '\t\t\t\tlocal p = hullMade[h[1]] or tpl:Clone()\n\t\t\t\tp.Name = "Brush"', 1)
        open(p, "w").write(s)
    print(f"{p}: hull brushes rebuilt with Hull collision")


if __name__ == "__main__":
    main(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else "~/code/active/games/roblox/T7Zombies/waxley/t7"))
