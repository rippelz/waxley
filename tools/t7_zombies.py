#!/usr/bin/env python3
"""T7Zombies' zombie rigs for Waxley, from tools/zombie/out (no uploads).

  python3 -I tools/t7_zombies.py [T7 checkout] [out .luau]

Writes one Roblox mesh (v2.00) per rig piece and the skin textures into the asset store under local ids
(keys zombie:<outfit>@N/<piece>, zombie:<outfit>@N/skin_<skin>), then a command-bar script that builds
ReplicatedStorage.ZombieModels.<outfit> the way tools/zombie/import.luau + publish.luau do: an R6 with the
five body MeshParts on Motor6Ds, an invisible Head box with the "Head mesh" and extras welded to it, and a
Skins folder of overlay SurfaceAppearances. Run the script in Waxley (argon exec) and save the place.
"""
import json
import os
import shutil
import struct
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bo3_local import STORE, Registry, write_if_changed  # noqa: E402

VERSION = 1  # bump when the mesh writing changes (Studio caches by id)
OUTFITS = ("soldier",)


def mesh_v2(p):
    """JSON piece (v / uv / n pools, t = 9 indices per triangle) -> v2 mesh centred on its bounds"""
    v = np.array(p["v"], np.float32).reshape(-1, 3)
    uv = np.array(p["uv"], np.float32).reshape(-1, 2)
    n = np.array(p["n"], np.float32).reshape(-1, 3)
    t = np.array(p["t"], np.int64).reshape(-1, 9)
    lo, hi = v.min(0), v.max(0)
    c = (lo + hi) / 2
    corners = []
    for k in range(3):
        corners.append(np.concatenate([v[t[:, k]] - c, n[t[:, 6 + k]], uv[t[:, 3 + k]], np.zeros((len(t), 1), np.float32)], 1))
    verts = np.stack(corners, 1).reshape(-1, 9).astype(np.float32)
    faces = np.arange(len(verts), dtype=np.uint32).reshape(-1, 3)
    head = b"version 2.00\n" + struct.pack("<HBBII", 12, 36, 12, len(verts), len(faces))
    return head + verts.tobytes() + faces.astype("<u4").tobytes(), c, hi - lo


def main(t7, out_lua):
    reg = Registry()
    lua = ["local _ = \"generated by waxley/tools/t7_zombies.py: local zombie rigs (ReplicatedStorage.ZombieModels)\"",
           "local DATA = {"]
    for outfit in OUTFITS:
        src = os.path.join(t7, "tools/zombie/out", outfit)
        d = json.load(open(os.path.join(src, f"Zombie_{outfit}.json")))
        lua.append(f'\t["{outfit}"] = {{ pieces = {{')
        for name, p in d["pieces"].items():
            if not p["t"]:
                continue
            data, c, size = mesh_v2(p)
            mid = reg.id(f"zombie:{outfit}@{VERSION}/{name}")
            write_if_changed(os.path.join(STORE, f"{mid}.mesh"), data)
            tint = d["extra"]["tint"].get(name)
            lua.append(f'\t\t["{name}"] = {{ id = {mid}, c = Vector3.new({c[0]:.5f}, {c[1]:.5f}, {c[2]:.5f}), '
                       f's = Vector3.new({size[0]:.5f}, {size[1]:.5f}, {size[2]:.5f}){f", tint = {json.dumps(tint)}" if tint else ""} }},')
        lua.append("\t}, skins = {")
        for skin, file in d["textures"].items():
            iid = reg.id(f"zombie:{outfit}@{VERSION}/skin_{skin}")
            for old in os.listdir(STORE):
                if old.split(".")[0] == str(iid):
                    os.remove(os.path.join(STORE, old))
            shutil.copyfile(os.path.join(src, file + ".png"), os.path.join(STORE, f"{iid}.png"))
            lua.append(f'\t\t{skin} = {iid},')
        j = d["joints"]
        lua.append(f'\t}}, eyeL = Vector3.new({j["eyeL"][0]}, {j["eyeL"][1]}, {j["eyeL"][2]}), '
                   f'eyeR = Vector3.new({j["eyeR"][0]}, {j["eyeR"][1]}, {j["eyeR"][2]}) }},')
    lua.append("}")
    lua.append(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "t7_zombies_rig.luau")).read())
    open(out_lua, "w").write("\n".join(lua))
    reg.save()
    print("wrote", out_lua)


if __name__ == "__main__":
    a = sys.argv[1:]
    main(a[0] if a else os.path.expanduser("~/code/active/games/roblox/T7Zombies"), a[1] if len(a) > 1 else "/tmp/wx-work/zombies.luau")
